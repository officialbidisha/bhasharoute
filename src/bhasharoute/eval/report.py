"""Render reports/metrics.json into reports/results.md (all numbers come from the harness)."""
from __future__ import annotations

from bhasharoute.config import REPORTS_DIR

ORDER = ["A_rules", "B_tfidf", "B_tfidf_aug", "C_xlmr_frozen", "C_xlmr_finetune", "C_xlmr_finetune_aug"]
DESC = {
    "A_rules": "A. keyword rules",
    "B_tfidf": "B. TF-IDF + LR",
    "B_tfidf_aug": "B. TF-IDF + LR (+code-mix aug)",
    "C_xlmr_frozen": "C. XLM-R frozen + MLP head",
    "C_xlmr_finetune": "C. XLM-R fine-tuned",
    "C_xlmr_finetune_aug": "C. XLM-R fine-tuned (+code-mix aug)",
}


def _p(x, digits=1):
    return "–" if x is None else f"{100 * x:.{digits}f}"


def _f(x, digits=3):
    return "–" if x is None else f"{x:.{digits}f}"


def write_report(results: dict) -> None:
    models = [m for m in ORDER if m in results]
    data = results.get("_data", {})
    L = ["# Results", "",
         "Auto-generated by `python -m bhasharoute.eval.harness` from `reports/metrics.json`.",
         f"Test rows: native in-domain {data.get('native_all')} (en {data.get('native_en')}, hi {data.get('native_hi')}, "
         f"bn {data.get('native_bn')}); held-out-domain OOD {data.get('ood_native')}; dev {data.get('dev')}.",
         "All thresholds and temperatures are fit on dev; test is scored once.", "",
         "## 1. Headline - human-translated test set (16 in-domain skills)", "",
         "| model | accuracy | macro-F1 | en F1 | hi F1 | bn F1 | ECE (calibrated) | OOD AUROC | side-effect gate recall |",
         "|---|---|---|---|---|---|---|---|---|"]
    for m in models:
        r, s = results[m], results[m]["sets"]
        L.append(f"| {DESC[m]} | {_p(s['native_all']['accuracy'])} | {_p(s['native_all']['macro_f1'])} | "
                 f"{_p(s['native_en']['macro_f1'])} | {_p(s['native_hi']['macro_f1'])} | {_p(s['native_bn']['macro_f1'])} | "
                 f"{_f(s['native_all'].get('ece_calibrated'))} | {_f(r['ood'].get('auroc'))} | "
                 f"{_p(s['native_all']['side_effect_gate']['recall'])} |")

    L += ["", "## 2. Robustness - script and code-mixing (macro-F1)", "",
          "`human_codemix` = native rows that MASSIVE's judges marked as Hindi/Bengali+English. "
          "The other three columns are synthetic (rule-generated) surface forms of test requests.", "",
          "| model | native hi+bn+en | human code-mixed | romanized (synthetic) | code-switched (synthetic) | romanized code-switched (synthetic) |",
          "|---|---|---|---|---|---|"]
    for m in models:
        s = results[m]["sets"]
        L.append(f"| {DESC[m]} | {_p(s['native_all']['macro_f1'])} | {_p(s['human_codemix']['macro_f1'])} | "
                 f"{_p(s['synthetic_romanized']['macro_f1'])} | {_p(s['synthetic_codemix']['macro_f1'])} | "
                 f"{_p(s['synthetic_codemix_romanized']['macro_f1'])} |")

    L += ["", "## 3. Calibration and abstention", "",
          "tau = confidence threshold keeping 95% of dev requests. OOD = test requests from held-out domains "
          "(cooking, takeaway) that the model never saw.", "",
          "| model | T | ECE before -> after | coverage @tau | selective acc @tau | OOD abstain @tau | OOD FPR@95TPR |",
          "|---|---|---|---|---|---|---|"]
    for m in models:
        r = results[m]
        c, na = r["calibration"], r["sets"]["native_all"]
        if c:
            sel = na["selective_at_tau"]
            L.append(f"| {DESC[m]} | {c['temperature']:.2f} | {_f(na['ece_uncalibrated'])} -> {_f(na['ece_calibrated'])} | "
                     f"{_p(sel['coverage'])} | {_p(sel['selective_accuracy'])} | {_p(r['ood']['abstain_rate_at_tau'])} | "
                     f"{_p(r['ood'].get('fpr_at_95tpr'))} |")
        else:
            L.append(f"| {DESC[m]} | – | – | {_p(1 - na['no_answer_rate'])} | – | {_p(r['ood']['abstain_rate_at_tau'])} (no keyword match) | – |")

    L += ["", "## 4. Side-effect detection (needs confirmation?)", "",
          "Model = side-effect head at the dev threshold for >=99% recall. Gate = lexical guard OR model "
          "(what the router actually uses). Unseen-domain = `takeaway_order` requests from the held-out domain.", "",
          "| model | head recall | head precision | gate recall | gate precision | unseen-domain gate recall |",
          "|---|---|---|---|---|---|"]
    for m in models:
        r, na = results[m], results[m]["sets"]["native_all"]
        L.append(f"| {DESC[m]} | {_p(na['side_effect_model']['recall'])} | {_p(na['side_effect_model']['precision'])} | "
                 f"{_p(na['side_effect_gate']['recall'])} | {_p(na['side_effect_gate']['precision'])} | "
                 f"{_p(r['ood']['unseen_domain_side_effect_gate_recall'])} |")

    L += ["", "## 5. Cross-lingual consistency", "",
          "Share of source requests whose surface forms all receive the same prediction.", "",
          "| model | en = hi = bn | native = romanized (hi, bn) |", "|---|---|---|"]
    for m in models:
        r = results[m]
        L.append(f"| {DESC[m]} | {_p(r['consistency_en_hi_bn'])} | {_p(r['consistency_native_vs_romanized'])} |")

    L += ["", "## 6. Challenge set (47 hand-written edge cases, AI-drafted, review pending)", "",
          "| model | routing correct | side effects gated | extra confirmations on read-only | per category |",
          "|---|---|---|---|---|"]
    for m in models:
        ch = results[m]["challenge"]
        cats = ", ".join(f"{k} {v}" for k, v in ch["per_category"].items())
        L.append(f"| {DESC[m]} | {_p(ch['routing_accuracy'])} | {ch['side_effects_gated']} | "
                 f"{ch['extra_confirmations_on_read_only']} | {cats} |")

    L += ["", "## 7. Efficiency (CPU, batch size 1, 4 threads, Apple M3)", "",
          "| model | size | p50 latency | p95 latency | int8 size | int8 p50 / p95 | int8 accuracy / macro-F1 |",
          "|---|---|---|---|---|---|---|"]
    for m in models:
        e = results[m].get("efficiency")
        if not e:
            continue
        if "latency_cpu_fp32" in e:
            lf, li = e["latency_cpu_fp32"], e.get("latency_cpu_int8")
            q = e.get("int8_native_all")
            L.append(f"| {DESC[m]} | {e['size_fp32_mb']:.0f} MB | {lf['p50_ms']:.1f} ms | {lf['p95_ms']:.1f} ms | "
                     + (f"{e['size_int8_mb']:.0f} MB | {li['p50_ms']:.1f} / {li['p95_ms']:.1f} ms | "
                        f"{_p(q['accuracy'])} / {_p(q['macro_f1'])} |" if li else "– | – | – |"))
        else:
            lc = e["latency_cpu"]
            size = f"{e['size_mb']:.0f} MB" if "size_mb" in e else "<1 MB"
            L.append(f"| {DESC[m]} | {size} | {lc['p50_ms']:.2f} ms | {lc['p95_ms']:.2f} ms | – | – | – |")

    best = max(models, key=lambda m: results[m]["sets"]["native_all"]["macro_f1"])
    err = results[best]["errors"]
    L += ["", f"## 8. Error analysis - {DESC[best]}", "", "Most frequent confusions (gold -> predicted):", ""]
    L += [f"- {c['gold']} -> {c['pred']}: {c['count']}" for c in err["top_confusions"]]
    for lang in ("en", "hi", "bn"):
        L += ["", f"Sampled errors ({lang}):", ""]
        L += [f"- `{e['text']}` gold **{e['gold']}**, predicted **{e['pred']}** (p={e['confidence']})" for e in err[lang]]
    ood = results[best]["ood"]
    if ood.get("false_accept_routed_to"):
        L += ["", f"OOD requests answered anyway were routed to: {ood['false_accept_routed_to']}"]
    ung = results[best]["challenge"]["ungated_side_effects"]
    L += ["", f"Challenge side-effect requests NOT gated by {DESC[best]}: " + (", ".join(f"`{t}`" for t in ung) or "none")]
    (REPORTS_DIR / "results.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {REPORTS_DIR / 'results.md'}")


README_START, README_END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def readme_results(results: dict) -> str:
    """Compact, auto-generated results block injected into README.md."""
    models = [m for m in ORDER if m in results]
    L = ["_Generated from `reports/metrics.json` by `python -m bhasharoute.eval.report`; "
         "full tables in [`reports/results.md`](reports/results.md)._", "",
         "**Human-translated test set** (8,157 requests, 16 skills) and **robustness slices** - macro-F1 %:", "",
         "| model | all | en | hi | bn | human code-mixed | romanized* | romanized code-switched* |",
         "|---|---|---|---|---|---|---|---|"]
    for m in models:
        s = results[m]["sets"]
        L.append(f"| {DESC[m]} | **{_p(s['native_all']['macro_f1'])}** | {_p(s['native_en']['macro_f1'])} | "
                 f"{_p(s['native_hi']['macro_f1'])} | {_p(s['native_bn']['macro_f1'])} | {_p(s['human_codemix']['macro_f1'])} | "
                 f"{_p(s['synthetic_romanized']['macro_f1'])} | {_p(s['synthetic_codemix_romanized']['macro_f1'])} |")
    L += ["", "\\* synthetic surface forms of held-out test requests (see [datasheet](reports/datasheet.md)).", "",
          "**Calibration, abstention, safety, cost:**", "",
          "| model | ECE before -> after | OOD AUROC | OOD abstain @tau | side-effect gate recall | p50 CPU latency |",
          "|---|---|---|---|---|---|"]
    for m in models:
        r = results[m]
        na, e = r["sets"]["native_all"], r.get("efficiency", {})
        ece = f"{na['ece_uncalibrated']:.3f} -> {na['ece_calibrated']:.3f}" if r["calibration"] else "–"
        lat = (e.get("latency_cpu_int8") or e.get("latency_cpu_fp32") or e.get("latency_cpu") or {}).get("p50_ms")
        tag = " (int8)" if "latency_cpu_int8" in e else ""
        L.append(f"| {DESC[m]} | {ece} | {_f(r['ood'].get('auroc'), 2)} | {_p(r['ood']['abstain_rate_at_tau'])} | "
                 f"{_p(na['side_effect_gate']['recall'])} | {'–' if lat is None else f'{lat:.2f} ms{tag}'} |")
    best = max(models, key=lambda m: results[m]["sets"]["native_all"]["macro_f1"])
    L += ["", f"Best on the human-translated test set: **{DESC[best]}**.", "",
          f"<img src=\"reports/figures/reliability_{best}.png\" width=\"360\" alt=\"reliability diagram\"> "
          f"<img src=\"reports/figures/confusion_{best}.png\" width=\"420\" alt=\"confusion matrix\">"]
    return "\n".join(L)


def update_readme(results: dict) -> None:
    from bhasharoute.config import ROOT
    path = ROOT / "README.md"
    text = path.read_text(encoding="utf-8")
    if README_START not in text:
        return
    head, rest = text.split(README_START, 1)
    _, tail = rest.split(README_END, 1)
    path.write_text(f"{head}{README_START}\n{readme_results(results)}\n{README_END}{tail}", encoding="utf-8")
    print(f"updated {path}")


if __name__ == "__main__":
    import json
    _results = json.loads((REPORTS_DIR / "metrics.json").read_text())
    write_report(_results)
    update_readme(_results)
